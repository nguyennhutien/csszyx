#!/usr/bin/env node

/**
 * Generate the engine's diagnostic codes for Rust and TypeScript from one list.
 *
 * Every diagnostic the engine renders carries a code beside its text, so a
 * gate, a config rule or an editor can tell kinds apart without matching the
 * English. The engine (Rust) produces the code and the compiler (TypeScript)
 * names it in its types and in the ids `csszyx check --rule` accepts. Two
 * hand-kept lists would drift the first time an id is added on one side, so the
 * list lives here and both files are written from it; `--check` fails CI when
 * either is stale.
 *
 * Usage:
 *   node scripts/gen-diagnostic-codes.mjs           # write
 *   node scripts/gen-diagnostic-codes.mjs --check   # CI gate
 */

import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

/**
 * Every code, in the order `csszyx check` lists them, with what it reports.
 *
 * The ids are public: `csszyx check --rule`, `check --json` and the config's
 * rule levels name them. Rename one only as a breaking change.
 *
 * @type {ReadonlyArray<readonly [id: string, doc: string]>}
 */
export const DIAGNOSTIC_CODES = [
    ['unknown-key', 'A key no sz table knows, likely a typo.'],
    ['canonical-key', 'An alias of a key, with the canonical spelling to write.'],
    ['removed-key', 'A key that was removed or replaced, with what to write instead.'],
    ['numeric-key', 'A numeric key, the mark of an array or spread passed as an sz object.'],
    ['closed-enum-value', 'A value a closed-enum key does not take.'],
    ['off-scale-value', "A spacing value off Tailwind's quarter-step scale."],
    ['numeric-font-weight', 'A font weight written as a numeric string.'],
    ['per-side-border-style', 'A border style on one side, which Tailwind cannot express.'],
    ['property-object', 'An object on a key that names a property, not a variant.'],
    ['non-variant-object', 'An object on a csszyx-owned key that is not a variant.'],
    ['unknown-field', 'A field a structured value (a mask layer) does not take.'],
    ['runtime-value', 'A runtime value on a key with no CSS-variable utility.'],
    ['unresolvable-spread', 'A spread in an sz object the build cannot resolve.'],
    ['style-override', 'A props spread that may override the style sz emits.'],
    ['szs-slot-map', 'An szs slot map the build cannot read, or one on a host element.'],
    ['sz-recover', 'An szRecover value the build cannot read.'],
    ['class-precedence', 'A runtime className beside sz, which sz overrides.'],
    ['duplicate-sz', 'An element with more than one sz attribute, merged in order.'],
    ['spread-split-class', 'Class names and sz on more than one side of a spread.'],
    ['moved-value', 'A value that moved to another key, with the key to write.'],
    ['global-before-group', 'A stand-alone keyword written before a group key that replaces it.'],
    ['runtime-family-conflict', 'A runtime value beside the other side of its key family.'],
    ['fallback-missing-css', 'A runtime fallback whose classes were never collected.'],
    ['fallback-nudge', 'A runtime fallback whose classes were still collected.'],
    ['merge-classifier-unavailable', 'A merge table this engine cannot read, so nothing merged.'],
    ['parse-error', 'A file the parser rejected, which contributes no classes.'],
    ['nesting-depth', 'A file nested deeper than the parser guard allows.'],
    ['unsupported-dynamic-sz', 'An sz attribute whose value the engine cannot read.'],
    ['ast-budget', 'A file over the AST budget, left unchanged.'],
    ['mangle-vars-hoist-skipped', 'A CSS variable mangleVars could not hoist to a component.'],
];

const repoRoot = path.resolve(import.meta.dirname, '..');
const rustPath = path.join(repoRoot, 'packages/core/src/transform/generated/diagnostic_codes.rs');
const tsPath = path.join(repoRoot, 'packages/compiler/src/diagnostic-codes.generated.ts');

/**
 * Convert a kebab-case id to its Rust enum variant.
 *
 * @param {string} id - Code id.
 * @returns {string} PascalCase variant name.
 */
export function variantName(id) {
    return id
        .split('-')
        .map(part => part.charAt(0).toUpperCase() + part.slice(1))
        .join('');
}

/**
 * Render the Rust module.
 *
 * @param {ReadonlyArray<readonly [string, string]>} codes - The code list.
 * @returns {string} Unformatted Rust source.
 */
export function renderRust(codes) {
    const variants = codes.map(([id, doc]) => `    /// ${doc}\n    ${variantName(id)},`).join('\n');
    const arms = codes.map(([id]) => `            Self::${variantName(id)} => "${id}",`).join('\n');
    const all = codes.map(([id]) => `    DiagnosticCode::${variantName(id)},`).join('\n');
    return `// @generated by scripts/gen-diagnostic-codes.mjs
// Do not edit by hand. Edit the list in that script instead.

use serde::{Deserialize, Serialize};

/// What kind of problem one engine diagnostic reports.
///
/// Rendered beside the diagnostic's text, so a consumer can tell kinds apart
/// without matching the English. The serialized form is the kebab-case id
/// \`csszyx check --rule\` accepts.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "kebab-case")]
pub enum DiagnosticCode {
${variants}
}

impl DiagnosticCode {
    /// The public id, as \`csszyx check --rule\` and \`check --json\` name it.
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
${arms}
        }
    }
}

/// Every code, in list order.
pub const DIAGNOSTIC_CODES: [DiagnosticCode; ${codes.length}] = [
${all}
];
`;
}

/**
 * Render the TypeScript module.
 *
 * @param {ReadonlyArray<readonly [string, string]>} codes - The code list.
 * @returns {string} TypeScript source.
 */
export function renderTypeScript(codes) {
    const union = codes.map(([id]) => `    | '${id}'`).join('\n');
    const list = codes.map(([id]) => `    '${id}',`).join('\n');
    return `// @generated by scripts/gen-diagnostic-codes.mjs
// Do not edit by hand. Edit the list in that script instead.

/** What kind of problem one engine diagnostic reports. */
export type SzDiagnosticCode =
${union};

/** Every code the engine produces, in the order \`csszyx check\` lists them. */
export const SZ_DIAGNOSTIC_CODES: readonly SzDiagnosticCode[] = [
${list}
];
`;
}

/**
 * Run rustfmt over generated source so the file matches the repo's Rust style.
 *
 * @param {string} source - Unformatted Rust source.
 * @returns {string} Formatted source, or the input when rustfmt is unavailable.
 */
function formatRust(source) {
    const dir = mkdtempSync(path.join(os.tmpdir(), 'csszyx-diagnostic-codes-'));
    const file = path.join(dir, 'diagnostic_codes.rs');
    try {
        writeFileSync(file, source);
        const result = spawnSync('rustfmt', ['--edition', '2021', file], { encoding: 'utf8' });
        if (result.status !== 0) {
            return source;
        }
        return readFileSync(file, 'utf8');
    } finally {
        rmSync(dir, { recursive: true, force: true });
    }
}

/**
 * Read a file, or the empty string when it does not exist.
 *
 * @param {string} file - Absolute path.
 * @returns {string} Its contents.
 */
function readOrEmpty(file) {
    try {
        return readFileSync(file, 'utf8');
    } catch {
        return '';
    }
}

/**
 * Write both generated modules, or verify the committed ones are current.
 *
 * @param {boolean} check - When true, report drift instead of writing.
 * @returns {number} Process exit code.
 */
export function main(check) {
    const outputs = [
        [rustPath, formatRust(renderRust(DIAGNOSTIC_CODES))],
        [tsPath, renderTypeScript(DIAGNOSTIC_CODES)],
    ];
    if (check) {
        const stale = outputs.filter(([file, generated]) => readOrEmpty(file) !== generated);
        for (const [file] of stale) {
            console.error(
                `[gen-diagnostic-codes] ${path.relative(repoRoot, file)} is stale. Run pnpm gen:diagnostic-codes.`,
            );
        }
        return stale.length === 0 ? 0 : 1;
    }
    for (const [file, generated] of outputs) {
        writeFileSync(file, generated);
        console.log(`[gen-diagnostic-codes] wrote ${path.relative(repoRoot, file)}`);
    }
    return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    process.exit(main(process.argv.includes('--check')));
}
