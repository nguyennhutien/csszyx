/**
 * Generate the CSS shorthand → longhand table.
 *
 * The merge decides whether a later class writes over an earlier one by
 * comparing the CSS properties each sets, and that comparison needs to know
 * that `padding` is the four `padding-*` properties and `gap` is `row-gap` plus
 * `column-gap`. Today that knowledge is a hand-kept list of Tailwind class
 * prefixes (`SHORTHAND_COVERAGE` in `@csszyx/runtime`), which has to be edited
 * every time Tailwind grows a utility family and was measured missing `gap` and
 * the scroll offsets.
 *
 * The relation is CSS, not Tailwind, so it is generated from `mdn-data` — the
 * dataset the CSS working group's own tooling publishes — and committed. A
 * hand-written copy of a spec table rots silently; a generated one fails
 * `--check` when the dataset moves.
 *
 * What is deliberately NOT here: which Tailwind class writes which property.
 * That is the project's own design system's answer, and it changes per project
 * (`@utility`, `@plugin`, a theme). This table is the half that is the same
 * everywhere.
 *
 * Usage:
 *   node scripts/gen-longhand-table.mjs           # write
 *   node scripts/gen-longhand-table.mjs --check   # CI: fail if stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const require = createRequire(import.meta.url);
const repoRoot = fileURLToPath(new URL('..', import.meta.url));
const outPath = join(repoRoot, 'packages/runtime/src/longhand-table.generated.ts');

/**
 * Properties whose mdn-data `computed` list is a real shorthand expansion.
 *
 * `computed` answers "what does the computed value of this property consist
 * of", which for a shorthand is its longhands and for a plain property is a
 * sentence about its own value. A list of length one is that second case
 * (`width` computes to `a percentage or absolute length`), so only lists of two
 * or more are read as an expansion.
 *
 * @param {Record<string, { computed?: unknown }>} properties - mdn-data's `css/properties.json`.
 * @returns {Map<string, string[]>} Shorthand → its longhands, in spec order.
 */
function collectShorthands(properties) {
    const shorthands = new Map();
    for (const [name, entry] of Object.entries(properties)) {
        // Vendor-prefixed and obsolete entries carry the same shape; the merge
        // only ever sees what Tailwind emits, so they cost nothing but noise.
        if (name.startsWith('-')) continue;
        const { computed } = entry;
        if (!Array.isArray(computed) || computed.length < 2) continue;
        if (computed.some(part => typeof part !== 'string' || !(part in properties))) continue;
        shorthands.set(name, [...computed]);
    }
    return shorthands;
}

/**
 * Every property a shorthand writes, following nested shorthands to the leaves.
 *
 * `border` expands to `border-width`, which is itself a shorthand for the four
 * sides — so a later `border-2` has to be known to write over an earlier
 * `border-t-2`, and only the transitive closure says so.
 *
 * @param {Map<string, string[]>} shorthands - Direct expansions.
 * @returns {Map<string, string[]>} Shorthand → every leaf it writes, sorted.
 */
function closeOver(shorthands) {
    const closed = new Map();
    /**
     * @param {string} name - Property to expand.
     * @param {Set<string>} seen - Names on the current path, to stop a cycle.
     * @returns {string[]} The leaves `name` writes.
     */
    const leaves = (name, seen) => {
        const direct = shorthands.get(name);
        if (direct === undefined || seen.has(name)) return [name];
        const next = new Set(seen).add(name);
        return direct.flatMap(part => leaves(part, next));
    };
    for (const name of shorthands.keys()) {
        closed.set(name, [...new Set(leaves(name, new Set()))].sort());
    }
    return closed;
}

/**
 * Render the generated module.
 *
 * @param {Map<string, string[]>} closed - Shorthand → leaves.
 * @param {string} version - The mdn-data version the table came from.
 * @returns {string} Module source.
 */
function render(closed, version) {
    const entries = [...closed.entries()]
        .sort(([a], [b]) => (a < b ? -1 : 1))
        .map(([name, parts]) => `    ['${name}', [${parts.map(p => `'${p}'`).join(', ')}]],`)
        .join('\n');
    return `// @generated by scripts/gen-longhand-table.mjs from mdn-data ${version}. Do not edit.
/**
 * CSS shorthand → every property it writes, to the leaves.
 *
 * Read by the merge to decide whether a later class writes over an earlier one:
 * \`padding\` covers the four \`padding-*\`, \`border\` covers the widths, styles
 * and colours of all four sides. Nested shorthands are already followed, so a
 * lookup is one step.
 *
 * Generated from the CSS dataset rather than hand-kept, because the relation is
 * CSS and does not change with Tailwind. Run \`pnpm gen:longhand\` after bumping
 * \`mdn-data\`; \`pnpm gen:longhand:check\` fails the build when this file and the
 * dataset disagree.
 *
 * @module
 */
export const LONGHANDS: ReadonlyMap<string, readonly string[]> = new Map([
${entries}
]);
`;
}

/**
 * Build the table and either write it or compare it.
 *
 * @returns {void}
 */
function main() {
    const properties = require('mdn-data/css/properties.json');
    const { version } = require('mdn-data/package.json');
    const closed = closeOver(collectShorthands(properties));
    const output = render(closed, version);

    if (process.argv.includes('--check')) {
        let current = '';
        try {
            current = readFileSync(outPath, 'utf8');
        } catch {
            /* missing counts as stale */
        }
        if (current !== output) {
            console.error(
                '[gen-longhand-table] longhand-table.generated.ts is stale. Run pnpm gen:longhand and commit.',
            );
            process.exitCode = 1;
            return;
        }
        console.log(`[gen-longhand-table] up to date (mdn-data ${version}).`);
        return;
    }

    writeFileSync(outPath, output);
    console.log(`[gen-longhand-table] wrote ${closed.size} shorthands from mdn-data ${version}.`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    main();
}
