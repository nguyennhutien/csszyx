#!/usr/bin/env node
/**
 * gen-migrate-golden.mjs
 *
 * Generates packages/cli/tests/generated/migrate-sz-golden.json — the sz object
 * `migrate` writes for every Tailwind prefix the compiler can emit.
 *
 * Round-tripping cannot see a wrong sz key. `rotate-x-45` read as
 * `rotate: 'x-45'` still lowers back to `rotate-x-45`, so
 * corpus-roundtrip.test.ts stays green on it; the wrongness only exists in the
 * intermediate sz object, which is what this golden records.
 *
 * The prefix set is exhaustive rather than sampled. The pinned corpora do not
 * contain the two classes that went wrong — `grep 'rotate-x\|border-bs'
 * scripts/corpus/*.txt` returns nothing — so a corpus-sampled golden would have
 * stayed silent on exactly the bug this exists to catch.
 *
 * Usage:
 *   node --import tsx/esm scripts/gen-migrate-golden.mjs           # write JSON
 *   node --import tsx/esm scripts/gen-migrate-golden.mjs --check   # CI: fail if stale
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

import { REVERSE_PROPERTY_MAP } from '../packages/cli/src/migrate/generated/reverse-property-map.js';
import { EXTRA_REVERSE_PREFIXES } from '../packages/cli/src/migrate/prefix-choice.js';
import { classNameToSzObject } from '../packages/cli/src/migrate/variant-parser.js';
import { PROPERTY_MAP } from '../packages/compiler/src/transform-core.js';

const repoRoot = path.resolve(import.meta.dirname, '..');
const outPath = path.join(repoRoot, 'packages/cli/tests/generated/migrate-sz-golden.json');

/**
 * The value forms each prefix is probed with.
 *
 * One sample per prefix is not enough: measured across the 268 prefixes, 92 of
 * them produce a DIFFERENT sz key depending on which of these three a class
 * carries. `border-2` is a width and `border-red-500` a colour; `drop-shadow-2`
 * is a colour and `drop-shadow-[3px]` a shadow. The table only supplies the
 * default — class-parser overrides it by reading the value — so a single sample
 * would pin the table half of the mapping and leave the decision half unpinned.
 */
const SAMPLE_VALUES = ['2', 'red-500', '[3px]'];

/**
 * Every prefix migrate should be able to read back.
 *
 * The union is deliberate. PROPERTY_MAP is what the compiler can emit, so it is
 * the authority on what migrate has to understand, and taking the input set
 * from there means a prefix dropping out of the reverse table changes the
 * golden's VALUES rather than quietly removing its inputs. The extras are class
 * roots no PROPERTY_MAP entry produces, and the reverse table's own keys are
 * included so a prefix that only exists there is still probed.
 *
 * @returns Sorted prefixes.
 */
export function goldenPrefixes() {
    return [
        ...new Set([
            ...Object.values(PROPERTY_MAP),
            ...Object.keys(EXTRA_REVERSE_PREFIXES),
            ...Object.keys(REVERSE_PROPERTY_MAP),
        ]),
    ].sort();
}

/**
 * Run every probe class through migrate's reverse parser.
 *
 * @returns The golden payload, ready to serialise.
 */
export function buildGolden() {
    const prefixes = {};
    let caseCount = 0;

    for (const prefix of goldenPrefixes()) {
        const cases = [];
        for (const value of SAMPLE_VALUES) {
            const className = `${prefix}-${value}`;
            const { szObject, unrecognized, keepInClassName } = classNameToSzObject(className);
            const entry = { class: className, sz: szObject };
            // Omitted when empty so the common case stays one line of diff, and
            // a prefix that stops being recognised shows up as an added field.
            if (unrecognized.length > 0) entry.unrecognized = unrecognized;
            if (keepInClassName.length > 0) entry.keepInClassName = keepInClassName;
            cases.push(entry);
            caseCount += 1;
        }
        prefixes[prefix] = cases;
    }

    return {
        $comment:
            'GENERATED by scripts/gen-migrate-golden.mjs. Do not edit by hand. Run pnpm gen:migrate-golden.',
        prefixCount: Object.keys(prefixes).length,
        caseCount,
        prefixes,
    };
}

/**
 * Write the golden, or fail when the committed copy is stale.
 */
function main() {
    const json = `${JSON.stringify(buildGolden(), null, 4)}\n`;

    if (process.argv.includes('--check')) {
        let current = '';
        try {
            current = readFileSync(outPath, 'utf8');
        } catch {
            /* missing counts as stale */
        }
        if (current !== json) {
            console.error(
                '[gen-migrate-golden] migrate-sz-golden.json is stale. Run pnpm gen:migrate-golden and commit.\n' +
                    'A diff here is a change to what migrate writes, not plumbing — read it before regenerating.',
            );
            process.exitCode = 1;
            return;
        }
        console.log('[gen-migrate-golden] up to date.');
        return;
    }

    mkdirSync(path.dirname(outPath), { recursive: true });
    writeFileSync(outPath, json);
    const { prefixCount, caseCount } = buildGolden();
    console.log(`[gen-migrate-golden] wrote ${caseCount} cases across ${prefixCount} prefixes.`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    main();
}
