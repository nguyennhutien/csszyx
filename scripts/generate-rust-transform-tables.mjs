#!/usr/bin/env node

// Generate Rust transform lookup tables from the TypeScript compiler source.

import { spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import ts from 'typescript';

const repoRoot = path.resolve(import.meta.dirname, '..');
const sourcePath = path.join(repoRoot, 'packages/compiler/src/transform-core.ts');
const outPath = path.join(repoRoot, 'packages/core/src/transform/generated/tables.rs');

const check = process.argv.includes('--check');
const sourceText = readFileSync(sourcePath, 'utf8');
const sourceFile = ts.createSourceFile(
    sourcePath,
    sourceText,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS,
);

const tables = {
    propertyMap: extractStringObject('PROPERTY_MAP'),
    variantMap: extractStringObject('VARIANT_MAP'),
    booleanToClass: extractStringObject('BOOLEAN_TO_CLASS'),
    booleanShorthands: extractStringSet('BOOLEAN_SHORTHANDS'),
    knownSpecialProperties: extractStringSet('KNOWN_SPECIAL_PROPERTIES'),
    removedBooleanSugar: extractObjectKeys('REMOVED_BOOLEAN_SUGAR'),
    knownVariants: extractStringSet('KNOWN_VARIANTS'),
    ariaStates: extractStringSet('ARIA_STATES'),
    specialVariants: extractStringSet('SPECIAL_VARIANTS'),
    suggestionMap: extractStringObject('SUGGESTION_MAP'),
    migrationNotes: extractStringObject('MIGRATION_NOTES'),
};

const generated = formatRust(renderRust(tables));

if (check) {
    const current = readFileSync(outPath, 'utf8');
    if (current !== generated) {
        console.error(
            '[generate-rust-transform-tables] generated tables are stale. Run pnpm gen:rust-tables.',
        );
        process.exit(1);
    }
    process.exit(0);
}

mkdirSync(path.dirname(outPath), { recursive: true });
writeFileSync(outPath, generated);
console.log(`[generate-rust-transform-tables] Wrote ${path.relative(repoRoot, outPath)}`);

function extractStringObject(name) {
    const declaration = findVariableDeclaration(name);
    const initializer = declaration.initializer;
    if (!initializer || !ts.isObjectLiteralExpression(initializer)) {
        fail(`${name} must be an object literal`);
    }

    const entries = [];
    for (const property of initializer.properties) {
        if (!ts.isPropertyAssignment(property)) {
            fail(`${name} contains a non-property assignment`);
        }

        const key = propertyNameToString(property.name);
        const value = stringLiteralToString(property.initializer);
        entries.push([key, value]);
    }

    return entries;
}

function extractStringSet(name) {
    const declaration = findVariableDeclaration(name);
    const initializer = declaration.initializer;
    if (
        !initializer ||
        !ts.isNewExpression(initializer) ||
        initializer.arguments?.length !== 1 ||
        !ts.isArrayLiteralExpression(initializer.arguments[0])
    ) {
        fail(`${name} must be new Set([...])`);
    }

    return initializer.arguments[0].elements.map(element => stringLiteralToString(element));
}

function findVariableDeclaration(name) {
    let found;

    visit(sourceFile);

    if (!found) {
        fail(`Could not find ${name}`);
    }

    return found;

    function visit(node) {
        if (
            ts.isVariableDeclaration(node) &&
            ts.isIdentifier(node.name) &&
            node.name.text === name
        ) {
            found = node;
            return;
        }

        ts.forEachChild(node, visit);
    }
}

function propertyNameToString(name) {
    if (ts.isIdentifier(name) || ts.isStringLiteral(name) || ts.isNumericLiteral(name)) {
        return name.text;
    }

    fail(`Unsupported property key: ${name.getText(sourceFile)}`);
}

function stringLiteralToString(node) {
    if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) {
        return node.text;
    }

    fail(`Expected string literal, got: ${node.getText(sourceFile)}`);
}

function renderRust({
    propertyMap,
    variantMap,
    booleanToClass,
    booleanShorthands,
    knownSpecialProperties,
    removedBooleanSugar,
    knownVariants,
    ariaStates,
    specialVariants,
    suggestionMap,
    migrationNotes,
}) {
    return `// @generated by scripts/generate-rust-transform-tables.mjs
// Do not edit by hand.
#![allow(dead_code, clippy::match_same_arms, clippy::too_many_lines)]
#![allow(clippy::redundant_pub_crate)]

/// Lookup the Tailwind utility prefix for a csszyx property key.
pub(crate) fn property_prefix(key: &str) -> Option<&'static str> {
    match key {
${renderMatchArms(propertyMap)}
        _ => None,
    }
}

/// Lookup the emitted variant prefix for a csszyx variant key.
pub(crate) fn variant_prefix(key: &str) -> Option<&'static str> {
    match key {
${renderMatchArms(variantMap)}
        _ => None,
    }
}

/// Canonical-key suggestion for a removed/aliased sz key.
pub(crate) fn key_suggestion(key: &str) -> Option<&'static str> {
    match key {
${renderMatchArms(suggestionMap)}
        _ => None,
    }
}

/// Migration note for a removed sz key whose replacement needs a sentence.
pub(crate) fn key_migration_note(key: &str) -> Option<&'static str> {
    match key {
${renderMatchArms(migrationNotes)}
        _ => None,
    }
}

/// Lookup emitted classes for boolean shorthand keys with custom class names.
pub(crate) fn boolean_class(key: &str) -> Option<&'static str> {
    match key {
${renderMatchArms(booleanToClass)}
        _ => None,
    }
}

/// Returns true when a boolean true value maps directly to a class.
pub(crate) fn is_boolean_shorthand(key: &str) -> bool {
    matches!(
        key,
${renderMatchPatterns(booleanShorthands)}
    )
}

/// Returns true when a property is lowered by a dedicated object branch.
pub(crate) fn is_known_special_property(key: &str) -> bool {
    matches!(
        key,
${renderMatchPatterns(knownSpecialProperties)}
    )
}

/// Returns true when a key is a removed boolean-sugar alias (flex/absolute/
/// italic/...). A \`true\` value on such a key emits no class — the canonical
/// key with a value is the only spelling.
pub(crate) fn is_removed_boolean_sugar(key: &str) -> bool {
    matches!(
        key,
${renderMatchPatterns(removedBooleanSugar)}
    )
}

/// Returns true when a key is a known csszyx variant name.
pub(crate) fn is_known_variant(key: &str) -> bool {
    matches!(
        key,
${renderMatchPatterns(knownVariants)}
    )
}

/// Returns true when a key is a standard ARIA state.
pub(crate) fn is_aria_state(key: &str) -> bool {
    matches!(
        key,
${renderMatchPatterns(ariaStates)}
    )
}

/// Returns true when a key is a parametric/scope variant stem (group, peer,
/// has, not, data, aria, supports) that combines with dash/bracket syntax.
pub(crate) fn is_special_variant(key: &str) -> bool {
    matches!(
        key,
${renderMatchPatterns(specialVariants)}
    )
}
`;
}

function extractObjectKeys(name) {
    const declaration = findVariableDeclaration(name);
    const initializer = declaration.initializer;
    if (!initializer || !ts.isObjectLiteralExpression(initializer)) {
        fail(`${name} must be an object literal`);
    }
    const keys = [];
    for (const property of initializer.properties) {
        if (!ts.isPropertyAssignment(property)) {
            fail(`${name} contains a non-property assignment`);
        }
        keys.push(propertyNameToString(property.name));
    }
    return keys;
}

function renderMatchArms(entries) {
    return entries
        .map(([key, value]) => `        ${rustString(key)} => Some(${rustString(value)}),`)
        .join('\n');
}

function renderMatchPatterns(entries) {
    return entries
        .map((key, index) => `${index === 0 ? '        ' : '        | '}${rustString(key)}`)
        .join('\n');
}

function rustString(value) {
    return JSON.stringify(value);
}

function formatRust(rustSource) {
    const tempDir = mkdtempSync(path.join(os.tmpdir(), 'csszyx-rust-tables-'));
    const tempPath = path.join(tempDir, 'tables.rs');

    try {
        writeFileSync(tempPath, rustSource);
        const result = spawnSync('rustfmt', [tempPath], { encoding: 'utf8' });
        if (result.status !== 0) {
            console.error(result.stderr);
            fail('rustfmt failed for generated tables');
        }

        return readFileSync(tempPath, 'utf8');
    } finally {
        rmSync(tempDir, { force: true, recursive: true });
    }
}

function fail(message) {
    console.error(`[generate-rust-transform-tables] ${message}`);
    process.exit(1);
}
