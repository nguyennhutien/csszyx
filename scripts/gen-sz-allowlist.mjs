/**
 * Generate the valid sz-key allowlist consumed by `@csszyx/dynamic`'s
 * `purifySz`.
 *
 * `purifySz` cleans UNTRUSTED sz objects (e.g. JSON-driven UI config that falls
 * through to runtime CSS injection) by dropping any key the compiler does not
 * recognise — an unknown key is either a typo that produces dead CSS or, worse,
 * an injection / prototype-pollution vector. The authoritative set of valid sz
 * property keys is owned by the compiler (`PROPERTY_MAP` ∪ `BOOLEAN_SHORTHANDS`),
 * so this allowlist is GENERATED from those tables — the same anti-drift
 * discipline as `gen:box-role` / `gen:key-tests`. A hand-maintained copy would
 * silently reject a real prop the moment the compiler gains one.
 *
 * The category (from the compiler's `PROPERTY_CATEGORY_MAP` via
 * `getPropertyCategory`) is emitted alongside each key for future per-category
 * value validation; today `purifySz` validates values generically.
 *
 * Usage:
 *   node --import tsx/esm scripts/gen-sz-allowlist.mjs           # write
 *   node --import tsx/esm scripts/gen-sz-allowlist.mjs --check   # CI: fail if stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { getPropertyCategory, PropertyCategory } from '../packages/compiler/src/property-types.js';
import { BOOLEAN_SHORTHANDS, PROPERTY_MAP } from '../packages/compiler/src/transform-core.js';

const repoRoot = join(fileURLToPath(import.meta.url), '..', '..');
const outPath = join(repoRoot, 'packages/dynamic/src/sz-allowlist.generated.ts');

/** Build the sorted [key, categoryName] list from the compiler tables. */
function build() {
    const keys = new Set([...Object.keys(PROPERTY_MAP), ...BOOLEAN_SHORTHANDS]);
    return [...keys].sort().map(key => {
        const category = PropertyCategory[getPropertyCategory(key)];
        if (typeof category !== 'string') {
            // getPropertyCategory always falls back to PASSTHROUGH, so this only
            // fires if the enum shape changes — fail loud rather than emit junk.
            throw new Error(`[gen-sz-allowlist] unclassified sz key: ${key}`);
        }
        return [key, category];
    });
}

function render(entries) {
    const lines = entries
        .map(([key, category]) => `    [${JSON.stringify(key)}, ${JSON.stringify(category)}],`)
        .join('\n');
    return `// GENERATED by scripts/gen-sz-allowlist.mjs — DO NOT EDIT.
//
// The authoritative allowlist of sz property keys (PROPERTY_MAP ∪
// BOOLEAN_SHORTHANDS), each mapped to its value category. Consumed by
// purifySz to drop unknown keys from untrusted sz input. Regenerate with
// \`pnpm gen:sz-allowlist\`; CI fails if this file drifts from the compiler.

/**
 * Every sz property key the compiler understands → its value category.
 * The key set is the security-relevant part; the category is informational
 * (for future per-category value validation).
 */
export const SZ_KEY_CATEGORY: ReadonlyMap<string, string> = new Map([
${lines}
]);
`;
}

const json = render(build());
const check = process.argv.includes('--check');

if (check) {
    let current = '';
    try {
        current = readFileSync(outPath, 'utf8');
    } catch {
        /* missing */
    }
    if (current !== json) {
        console.error(
            '[gen-sz-allowlist] sz-allowlist.generated.ts is stale. Run pnpm gen:sz-allowlist and commit.',
        );
        process.exit(1);
    }
    console.log('[gen-sz-allowlist] up to date.');
    process.exit(0);
}

writeFileSync(outPath, json);
console.log(`[gen-sz-allowlist] wrote ${build().length} sz keys.`);
