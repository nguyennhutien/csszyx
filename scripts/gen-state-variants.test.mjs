// The state-variant table tells the runtime which bare state names the
// Tailwind csszyx builds with serves as a variant, and how `unserved-variant`
// words each one. The decisions in it — which list a name comes from, what
// counts as served, how a version differs from the pin — are pinned here on
// hand-made answers, without a Tailwind install.
import assert from 'node:assert/strict';
import test from 'node:test';

import {
    assertHtmlOnlyServed,
    HTML_STATE_ATTRIBUTES,
    htmlOnlyStateNames,
    renderStateVariants,
    servedStateVariants,
    stateVariantDifferences,
    stateVariantForms,
} from './gen-state-variants.mjs';

test('words each ARIA state by whether it is an HTML attribute too, in name order', () => {
    const aria = new Set(['hidden', 'expanded']);
    const forms = stateVariantForms(aria, ['open', 'hidden']);

    assert.deepEqual(
        [...forms],
        [
            ['expanded', 'aria'],
            ['hidden', 'attribute-or-aria'],
        ],
    );
    // An HTML attribute that is no ARIA state is no name of the table.
    assert.deepEqual(htmlOnlyStateNames(aria, ['open', 'hidden', 'inert']), ['inert', 'open']);
});

test('fails loudly when the pin stops serving an attribute the table leaves out', () => {
    assert.doesNotThrow(() =>
        assertHtmlOnlyServed(['inert', 'open'], ['checked', 'inert', 'open']),
    );
    assert.throws(
        () => assertHtmlOnlyServed(['default', 'inert', 'open'], ['open']),
        /tailwindcss serves no bare `default`, `inert` variant/,
    );
});

test('lists the HTML boolean attributes measured for the ADR, sorted and unique', () => {
    assert.deepEqual(HTML_STATE_ATTRIBUTES, [...new Set(HTML_STATE_ATTRIBUTES)].sort());
    for (const name of ['checked', 'disabled', 'hidden', 'open', 'readonly', 'required']) {
        assert.ok(HTML_STATE_ATTRIBUTES.includes(name), name);
    }
});

test('counts a name served when Tailwind writes CSS for it as a bare variant', () => {
    const asked = [];
    const served = servedStateVariants(['hidden', 'checked', 'open'], classes => {
        asked.push(...classes);
        return classes.filter(name => name.startsWith('hidden:'));
    });

    assert.deepEqual(served, ['checked', 'open']);
    // One question per name, on a utility every Tailwind v4 serves.
    assert.deepEqual(asked, ['hidden:flex', 'checked:flex', 'open:flex']);
});

test('names each state whose answer on a version differs from the pin', () => {
    assert.deepEqual(
        stateVariantDifferences(
            ['checked', 'inert'],
            ['checked', 'open'],
            ['checked', 'hidden', 'inert', 'open'],
        ),
        ['inert: served here, not by the pin', 'open: served by the pin, not here'],
    );
    assert.deepEqual(stateVariantDifferences(['checked'], ['checked'], ['checked']), []);
});

test('renders a module that states the Tailwind it was measured on', () => {
    const source = renderStateVariants(
        new Map([
            ['expanded', 'aria'],
            ['hidden', 'attribute-or-aria'],
        ]),
        ['hidden'],
        '4.3.3',
    );

    assert.match(
        source,
        /^\/\/ @generated by scripts\/gen-state-variants\.mjs from tailwindcss 4\.3\.3/,
    );
    assert.match(source, /export const STATE_VARIANT_FORMAT = 1;/);
    assert.match(source, /export type StateVariantForm = 'aria' \| 'attribute-or-aria';/);
    assert.match(
        source,
        /STATE_VARIANT_FORMS: Readonly<Record<string, StateVariantForm>> = \{\n {4}expanded: 'aria',\n {4}hidden: 'attribute-or-aria',\n\};/,
    );
    assert.match(source, /SERVED_STATE_VARIANTS: readonly string\[\] = \[\n {4}'hidden',\n\];/);
});
